/**
 * Turns Claude Code agent files (agents/*.md: YAML frontmatter + system prompt) into "dispatch cards" for Codex.
 *
 * Codex (checked on codex-cli 0.163.0, `codex exec`) cannot select a custom agent: `collaboration.spawn_agent` takes
 * `task_name`, `message`, `fork_turns`, `model` and `reasoning_effort`, and neither `.codex/agents/*.toml` nor
 * `[agents.<role>]` in config.toml makes a role selectable. So a card carries what the main Codex agent needs to
 * emulate the agent: the spawn parameters (mapped from the Claude frontmatter) and the instructions to send as `message`.
 * The cards ship inside the dev-workflow skill, so they reach every Codex install the plugin reaches.
 *
 *  - `model`: Claude alias -> Codex model, see MODELS. Unknown or missing = omitted (inherits the parent's model).
 *  - `effort` -> `reasoning_effort`.
 *  - `tools` has no Codex equivalent (the sub-agent inherits the parent's tools and sandbox); the card says so.
 */

import { readdirSync, readFileSync } from "fs";
import { join } from "path";

/**
 * Claude model alias -> Codex model slug. Tiers follow the descriptions in Codex's model list
 * (`~/.codex/models_cache.json`): luna "fast and affordable model for easier tasks", sol "latest workhorse model for
 * coding and everyday work", astra "frontier intelligence for the most demanding work".
 */
export const MODELS = { haiku: "gpt-6-luna", sonnet: "gpt-6.1-sol", opus: "gpt-6-astra" };

/** First characters of every generated card; sync-codex only deletes files that carry it. */
export const CARD_MARKER = "<!-- Generated by scripts/sync-codex.mjs";

const FRONTMATTER = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/;
const EFFORTS = new Set(["low", "medium", "high", "xhigh", "max"]);

/** A plain or quoted single-line scalar; block scalars, flow collections and trailing comments are rejected. */
function scalar(file, raw) {
  const quoted = /^(["'])(.*)\1$/.exec(raw);
  if (quoted) return quoted[2];
  if (/^[>|\[{&*!]/.test(raw) || /\s#/.test(raw)) throw new Error(`${file}: unsupported YAML value "${raw}"`);
  return raw;
}

function parseAgent(file, text) {
  const match = FRONTMATTER.exec(text);
  if (!match) throw new Error(`${file}: no YAML frontmatter`);
  const meta = {};
  for (const line of match[1].split("\n")) {
    const pair = /^([A-Za-z_]+):\s*(.+)$/.exec(line);
    if (!pair) throw new Error(`${file}: unsupported frontmatter line "${line}" (only single-line "key: value")`);
    meta[pair[1]] = scalar(file, pair[2].trim());
  }
  for (const key of ["name", "description"]) {
    if (!meta[key]) throw new Error(`${file}: frontmatter lacks "${key}"`);
  }
  if (!/^[a-z0-9][a-z0-9-]*$/.test(meta.name) || `${meta.name}.md` !== file) {
    throw new Error(`${file}: name "${meta.name}" must be lowercase letters, digits and hyphens and match the file name`);
  }
  if (meta.effort && !EFFORTS.has(meta.effort)) throw new Error(`${file}: unknown effort "${meta.effort}"`);
  return { file, meta, body: match[2].trim() };
}

function toCard({ file, meta, body }) {
  const params = ['`fork_turns: "none"`', `\`task_name: "${meta.name.replaceAll("-", "_")}"\``];
  const model = MODELS[meta.model];
  if (model) params.push(`\`model: "${model}"\``);
  if (meta.effort) params.push(`\`reasoning_effort: "${meta.effort}"\``);
  const tools = meta.tools ? ` Claude restricted it to ${meta.tools}; Codex can't, so stay within that yourself.` : "";
  return `${CARD_MARKER} from agents/${file}. Do not edit. -->
# ${meta.name} (Codex dispatch card)

${meta.description}

Codex can't select agent files. Spawn it with \`collaboration.spawn_agent\`: ${params.join(", ")}, and \`message\` = the instructions below, then a blank line and your task inputs.${tools}

## Instructions

${body}
`;
}

/** Map of `<name>.md` to its card, for every agents/*.md in `agentsDir`. */
export function buildCodexAgentCards(agentsDir) {
  const files = readdirSync(agentsDir).filter((name) => name.endsWith(".md")).sort();
  return Object.fromEntries(
    files.map((file) => {
      const agent = parseAgent(file, readFileSync(join(agentsDir, file), "utf8"));
      return [`${agent.meta.name}.md`, toCard(agent)];
    }),
  );
}
